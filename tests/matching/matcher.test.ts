import assert from "node:assert/strict";
import { describe, it } from "node:test";

import { blackList } from "../../src/core/blacklist.js";
import { Matcher } from "../../src/matching/matcher.js";
import { hasControlChars } from "../../src/utils/normalize.js";
import {
  launchesSteamGame,
  steamGameIdFromWmClass,
} from "../../src/utils/steam.js";
import { HeuristicStrategy } from "../../src/matching/strategies/heuristic.js";
import type { MappedWindow } from "../../src/types.js";
import { APPS } from "../fixtures/apps.js";
import { catalogOf } from "../helpers.js";
import { legacyIsBlackListed } from "../legacy/legacyMatcher.js";

const win = (wmClass: string, title = "", appId = ""): MappedWindow => ({
  wmClass,
  title,
  appId,
});

describe("matcher", () => {
  const catalog = catalogOf(APPS);
  const matcher = new Matcher();

  it("prefers the deterministic match", () => {
    const result = matcher.match(win("broforce.x86_64", "Broforce"), catalog);
    assert.equal(result?.matchType, "deterministic");
    assert.equal(result?.app.id, "Broforce.desktop");
  });

  it("matches proton games by the steam exec", () => {
    const result = matcher.match(win("steam_app_1091500"), catalog);
    assert.equal(result?.app.id, "Cyberpunk 2077.desktop");
    assert.equal(result?.reason, "steam exec");
  });

  it("does not match steam sub processes to steam itself", () => {
    const result = matcher.match(win("steam_app_999999"), catalog);
    assert.notEqual(result?.app.id, "steam.desktop");
  });

  it("never picks an entry generated by the extension (R1)", () => {
    for (const w of [
      win("steam_app_1808500", "ARC Raiders"),
      win("steam_app_4704690"),
    ]) {
      assert.equal(matcher.match(w, catalog), null);
    }
  });

  it("reports the runner-up score", () => {
    const result = new HeuristicStrategy().match(
      win("hunt.exe", "Hunt: Showdown 1896"),
      catalog,
    );
    assert.equal(result?.app.id, "Hunt Showdown 1896.desktop");
    assert.ok(result!.runnerUpScore < result!.score);
  });

  it("ignores generic short desktop ids", () => {
    assert.equal(matcher.match(win("GTK Application"), catalog), null);
  });
});

describe("steam", () => {
  it("extracts the game id from proton wm classes", () => {
    assert.equal(steamGameIdFromWmClass("steam_app_480"), "480");
    assert.equal(steamGameIdFromWmClass("Steam_App_480"), "480");
    assert.equal(steamGameIdFromWmClass("steam_app_ubiconnect"), null);
  });

  it("matches the game id whole (R10)", () => {
    assert.ok(launchesSteamGame("steam steam://rungameid/480", "480"));
    assert.ok(launchesSteamGame("xdg-open steam://rungameid/480 --foo", "480"));
    assert.ok(!launchesSteamGame("steam steam://rungameid/4800", "480"));
  });
});

describe("blacklist", () => {
  const patterns = ["org.gnome*", "*portal", "*foo*", "steam", "qt"];
  blackList.setPatterns(patterns);

  it("supports exact, prefix, suffix and contains patterns, case insensitive", () => {
    assert.ok(blackList.isBlackListed("org.gnome.Nautilus"));
    assert.ok(blackList.isBlackListed("xdg-desktop-PORTAL"));
    assert.ok(blackList.isBlackListed("myfoobar"));
    assert.ok(blackList.isBlackListed("Steam"));
    assert.ok(!blackList.isBlackListed("steam_app_1"));
    assert.ok(!blackList.isBlackListed(""));
  });

  it("also applies to short wm classes (R7)", () => {
    assert.equal(legacyIsBlackListed(patterns, "qt"), false);
    assert.ok(blackList.isBlackListed("qt"));
  });

  it("replaces the patterns when they change", () => {
    blackList.setPatterns(["other"]);
    assert.ok(!blackList.isBlackListed("Steam"));
    assert.ok(blackList.isBlackListed("other"));
    blackList.setPatterns(patterns);
  });
});

describe("normalize", () => {
  it("detects control characters", () => {
    assert.ok(hasControlChars("evil\nExec=rm"));
    assert.ok(!hasControlChars("GTK Application"));
  });
});
