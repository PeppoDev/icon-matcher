import assert from "node:assert/strict";
import { describe, it } from "node:test";

import { headerComment, parseLegacyHeader } from "../../src/utils/metadata.js";
import { generatedFileName } from "../../src/utils/naming.js";

describe("generated file names", () => {
  it("keeps safe wm classes verbatim, so older files are still found", () => {
    for (const wm of ["steam_app_1091500", "GTK Application", "warhammer 40000 space marine 2 - retail.exe", "Broforce.x86_64"]) {
      assert.equal(generatedFileName(wm), wm);
    }
  });

  it("never escapes the generated directory", () => {
    // "" and ".." are rejected by the fixer before reaching this function
    for (const wm of ["../../../.config/autostart/evil", "/etc/passwd", ".hidden", "a\nb"]) {
      const stem = generatedFileName(wm);
      assert.doesNotMatch(stem, /[\/\n]/, wm);
      assert.ok(!stem.startsWith("."), wm);
      assert.ok(stem.length > 0, wm);
    }
  });
});

describe("metadata", () => {
  it("parses the header written before the X-IconMatcher keys", () => {
    const legacy = [
      "# Auto-generated by the Icon Fix GNOME Shell extension.",
      "# Source: /home/user/.local/share/applications/Cyberpunk 2077.desktop",
      "# Search type: heuristic",
      "# Score (deterministic is always 100): 99",
      "# Added StartupWMClass=steam_app_1091500",
      "[Desktop Entry]",
      "Name=Cyberpunk 2077",
    ].join("\n");

    assert.deepEqual(parseLegacyHeader(legacy), {
      source: "/home/user/.local/share/applications/Cyberpunk 2077.desktop",
      matchType: "heuristic",
      score: 99,
    });
  });

  it("tolerates missing fields", () => {
    assert.deepEqual(parseLegacyHeader("# Source: /a.desktop\n# Score (x): \n"), {
      source: "/a.desktop",
    });
  });

  it("writes a header that mentions the source", () => {
    const header = headerComment({
      kind: "ghost",
      source: "/a.desktop",
      wmClass: "wm",
      matchType: "heuristic",
      score: 70,
    });
    assert.match(header, /Source: \/a\.desktop/);
    assert.doesNotMatch(header, /^#/m);
  });
});
