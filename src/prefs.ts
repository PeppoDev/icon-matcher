import Adw from "gi://Adw";
import Gio from "gi://Gio";
import Gtk from "gi://Gtk";

import {
  ExtensionPreferences,
  gettext as _,
} from "resource:///org/gnome/Shell/Extensions/js/extensions/prefs.js";
import { SettingsKey } from "./constants.js";
import { logger } from "./core/logger.js";
import { GhostHandler } from "./entries/ghostHandler.js";

export default class IconMatcherPreferences extends ExtensionPreferences {
  #store = new GhostHandler();

  fillPreferencesWindow(window: Adw.PreferencesWindow): Promise<void> {
    const settings = this.getSettings();
    logger.setDebug(settings.get_boolean(SettingsKey.debug));

    const page = new Adw.PreferencesPage({
      title: _("General"),
      iconName: "preferences-system-symbolic",
    });

    page.add(this.#debugGroup(settings));
    page.add(this.#blacklistGroup(settings));
    page.add(this.#actionsGroup(window));

    window.add(page);
    return Promise.resolve();
  }

  #debugGroup(settings: Gio.Settings): Adw.PreferencesGroup {
    const group = new Adw.PreferencesGroup({
      title: _("Debug"),
      description: _("Debug and troubleshooting options"),
    });

    const debugEnabled = new Adw.SwitchRow({
      title: _("Enable debug logs"),
      subtitle: _("Print extension logs to the journal"),
    });
    settings.bind(
      SettingsKey.debug,
      debugEnabled,
      "active",
      Gio.SettingsBindFlags.DEFAULT,
    );
    group.add(debugEnabled);

    return group;
  }

  #blacklistGroup(settings: Gio.Settings): Adw.PreferencesGroup {
    const group = new Adw.PreferencesGroup({
      title: _("Blacklisted WM Classes"),
      description: _("Ignored WM_CLASS patterns"),
    });

    const patterns = new Adw.EntryRow({
      title: _("Patterns"),
      showApplyButton: true,
    });
    patterns.set_text(settings.get_strv(SettingsKey.blacklist).join(", "));
    patterns.connect("apply", () => {
      const values = patterns
        .get_text()
        .split(",")
        .map((v) => v.trim())
        .filter(Boolean);

      settings.set_strv(SettingsKey.blacklist, values);
    });
    group.add(patterns);

    group.add(
      new Adw.ActionRow({
        title: _("Pattern examples"),
        subtitle: _(
          "example = exact, example* = prefix, *example = suffix, *example* = contains",
        ),
      }),
    );

    return group;
  }

  #actionsGroup(window: Adw.PreferencesWindow): Adw.PreferencesGroup {
    const group = new Adw.PreferencesGroup({
      title: _("Actions"),
      description: _("Perform actions on auto generated files."),
    });

    const syncRow = new Adw.ActionRow({
      title: _("Sync information"),
      subtitle: _(
        "Sync information between the original and autogenerated file.",
      ),
    });
    const syncButton = this.#actionButton(_("Sync Files"));
    syncButton.connect("clicked", () => this.#sync(window));
    syncRow.add_suffix(syncButton);
    group.add(syncRow);

    const resetRow = new Adw.ActionRow({
      title: _("Restore defaults"),
      subtitle: _("Delete generated desktop files"),
    });
    const resetButton = this.#actionButton(_("Reset"), ["destructive-action"]);
    resetButton.connect("clicked", () => this.#confirmReset(window));
    resetRow.add_suffix(resetButton);
    group.add(resetRow);

    return group;
  }

  #actionButton(label: string, extraClasses: string[] = []): Gtk.Button {
    return new Gtk.Button({
      label,
      cssClasses: [...extraClasses, "action-button"],
      halign: Gtk.Align.END,
      valign: Gtk.Align.CENTER,
      widthRequest: 140,
      heightRequest: 40,
    });
  }

  async #sync(window: Adw.PreferencesWindow) {
    try {
      const { synced, skipped, failed, deleted } = await this.#store.sync();
      this.#toast(
        window,
        _("Synced %d, deleted %d, skipped %d, failed %d")
          .replace("%d", `${synced}`)
          .replace("%d", `${deleted}`)
          .replace("%d", `${skipped}`)
          .replace("%d", `${failed}`),
      );
    } catch (err) {
      logger.error("Sync failed", err);
      this.#toast(window, _("Sync failed, check the logs"));
    }
  }

  #confirmReset(window: Adw.PreferencesWindow) {
    const dialog = new Adw.AlertDialog({
      heading: _("Reset generated desktop files?"),
      body: _(
        "All desktop files generated by the extension will be permanently removed.",
      ),
    });

    dialog.add_response("cancel", _("Cancel"));
    dialog.add_response("confirm", _("Reset"));
    dialog.set_response_appearance(
      "confirm",
      Adw.ResponseAppearance.DESTRUCTIVE,
    );
    dialog.set_default_response("cancel");
    dialog.set_close_response("cancel");

    dialog.connect("response", (_dialog, response) => {
      if (response === "confirm") this.#reset(window);
    });
    dialog.present(window);
  }

  async #reset(window: Adw.PreferencesWindow) {
    try {
      const deleted = await this.#store.reset();
      this.#toast(window, _("Removed %d files").replace("%d", `${deleted}`));
    } catch (err) {
      logger.error("Reset failed", err);
      this.#toast(window, _("Reset failed, check the logs"));
    }
  }

  #toast(window: Adw.PreferencesWindow, title: string) {
    window.add_toast(new Adw.Toast({ title }));
  }
}
